-- ── 1. preset_trips ─────────────────────────────────────────────────────────
-- The published preset itineraries the Browse tab serves. `data` is the whole
-- itinerary document; the flat columns beside it are the filter/sort facets.
-- The CHECK constraints are written inline and unnamed on purpose: Postgres
-- then auto-names them preset_trips_<column>_check, which is what is live.
--
-- SAFE ON PRODUCTION: `if not exists` makes this a no-op — the table exists,
-- so the whole definition (including the CHECKs) is skipped. It cannot alter
-- or re-check the 20 live rows.
create table if not exists public.preset_trips (
  slug             text        not null primary key,
  data             jsonb       not null,
  vibes            text[]      not null default '{}'::text[],
  region           text        not null,
  duration_bucket  text        not null check (duration_bucket in ('weekend', 'one-week', 'two-weeks', 'month')),
  budget_tier      text        not null check (budget_tier in ('$', '$$', '$$$', '$$$$')),
  origin_region    text        not null default 'us-east'::text,
  nights           integer     not null,
  est_cost         numeric     not null,
  categories       text[]      not null default '{}'::text[],
  hero_image_url   text,
  staff_pick       boolean     not null default false,
  status           text        not null default 'published'::text check (status in ('draft', 'published')),
  source           text        not null default 'curated'::text check (source in ('curated', 'generated')),
  refresh_status   text        not null default 'fresh'::text check (refresh_status in ('fresh', 'refreshing', 'failed')),
  refreshed_at     timestamptz,
  clone_count      integer     not null default 0,
  impression_count integer     not null default 0,
  view_count       integer     not null default 0,
  created_at       timestamptz not null default now()
);

-- ── 2. preset_events ────────────────────────────────────────────────────────
-- Append-only engagement log behind preset_trips' impression/view/clone
-- counters. `id` is GENERATED ALWAYS AS IDENTITY live (not a serial/sequence
-- default), so it is written that way here — `generated by default` would
-- accept a client-supplied id and drift from prod.
--
-- SAFE ON PRODUCTION: `if not exists` makes this a no-op. The FK to
-- preset_trips(slug) is only created on a from-scratch build, so no existing
-- row is re-validated and no lock is taken on the live preset_trips.
create table if not exists public.preset_events (
  id          bigint      not null generated always as identity primary key,
  preset_slug text        not null references public.preset_trips (slug) on delete cascade,
  kind        text        not null check (kind in ('impression', 'view', 'use')),
  created_at  timestamptz not null default now()
);

-- ── 3. Indexes ──────────────────────────────────────────────────────────────
-- SAFE ON PRODUCTION: both already exist, and `if not exists` skips them
-- without rebuilding. (Not CONCURRENTLY: a plain `create index` cannot run
-- inside a transaction block alongside the rest of this file, and on a
-- from-scratch build the tables are empty so there is nothing to lock.)

-- Facet filter: `categories && '{...}'` on the Browse tab.
-- NOTE: `vibes` is filtered the same way but has NO index live. Left as-is —
-- this file records production, it does not improve it. See the report.
create index if not exists preset_trips_categories_idx
  on public.preset_trips using gin (categories);

-- Recency scan for the counter rollups: newest first, then by preset.
create index if not exists preset_events_recent_idx
  on public.preset_events using btree (created_at desc, preset_slug);

-- ── 4. Row Level Security ───────────────────────────────────────────────────
-- Both tables have RLS enabled live. Note that on this project they would get
-- it anyway: the `ensure_rls` event trigger runs rls_auto_enable() on
-- ddl_command_end for every new table in `public` (see ../SCHEMA_SNAPSHOT.sql).
-- Enabling it explicitly keeps the file correct on a plain Postgres that has
-- no such event trigger.
--
-- SAFE ON PRODUCTION: `enable row level security` on a table that already has
-- it is a no-op and touches no rows or policies.
alter table public.preset_trips  enable row level security;
alter table public.preset_events enable row level security;

-- preset_trips: anyone may read a PUBLISHED preset; drafts are invisible to
-- anon/authenticated. Granted to PUBLIC (no `to` clause), matching live.
-- Writes have no policy, so only the service role (which bypasses RLS) can
-- insert/update/delete.
--
-- SAFE ON PRODUCTION: guarded by an existence check on the policy, so the
-- live policy is left exactly as it is. A `drop policy if exists` +
-- `create policy` pair would be idempotent in the loose sense but would
-- silently replace the live definition — which is the one thing this file
-- must not do.
do $$
begin
  if not exists (
    select 1 from pg_policy
     where polrelid = 'public.preset_trips'::regclass
       and polname  = 'preset_trips_public_read'
  ) then
    create policy preset_trips_public_read on public.preset_trips
      for select using (status = 'published'::text);
  end if;
end $$;

-- preset_events: RLS is enabled and there are DELIBERATELY NO POLICIES live,
-- which denies every anon/authenticated read AND write. Only the service role
-- reaches this table. Nothing to create here — this comment records the
-- absence so a future reader does not "fix" it by inventing a policy.
--
-- NOTE: the table-level grants say otherwise (anon and authenticated hold
-- INSERT/SELECT/UPDATE/DELETE), but those come from Supabase's
-- `alter default privileges` on schema public, not from any migration — the
-- ACL on both tables is byte-identical to the schema default ACL. RLS is what
-- actually gates access, so the grants are inert. No grant/revoke statement
-- is issued here for the same reason: on Supabase the default privileges
-- reapply themselves, and issuing explicit grants would make this file
-- diverge from prod rather than match it. (Same approach as 012.)

