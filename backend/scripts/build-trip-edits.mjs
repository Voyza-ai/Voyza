/**
 * Bundles the website's pure trip-edit functions (frontend/lib/cityEdit.ts,
 * transportChange.ts, tripTotals.ts and what they import) into
 * src/generated/tripEditsBundle.ts, so the text bot saves a YES with the SAME
 * code the results page runs on Accept — no hand-copied port to drift.
 *
 *   npm run build:trip-edits        (re-run after changing those frontend files;
 *                                    src/tests/tripEditsBundle.test.ts fails if stale)
 *
 * Emitted as a .ts file (with @ts-nocheck) because tsc only copies .ts into
 * dist/ — see scripts/assert-build-output.mjs.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER =
  '// @ts-nocheck\n/* eslint-disable */\n' +
  '// GENERATED by scripts/build-trip-edits.mjs from frontend/lib — do not edit.\n';

export async function bundleTripEdits() {
  const r = await build({
    entryPoints: [join(backendRoot, 'scripts', 'tripEditsEntry.ts')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'es2022',
    tsconfig: join(backendRoot, '..', 'frontend', 'tsconfig.json'),
    write: false,
    legalComments: 'none',
    logLevel: 'silent',
  });
  return HEADER + r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(backendRoot, 'src', 'generated', 'tripEditsBundle.ts');
  const fresh = await bundleTripEdits();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(out, 'utf8'); } catch { /* missing */ }
    if (current !== fresh) {
      console.error('src/generated/tripEditsBundle.ts is out of date with frontend/lib — run: npm run build:trip-edits');
      process.exit(1);
    }
    console.log('trip-edits bundle is up to date');
  } else {
    writeFileSync(out, fresh);
    console.log(`wrote ${out}`);
  }
}
