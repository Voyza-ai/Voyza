import { Trip, City, Hotel } from './types';
import { rankHotels } from './hotelScore';

/** Helper: build a city, ranking its hotels and selecting the top one. */
function buildCity(
  city: Omit<City, 'hotels' | 'selectedHotelIndex' | 'hotel'> & { hotels: Hotel[] }
): City {
  const ranked = rankHotels(city.hotels);
  return {
    ...city,
    hotels: ranked,
    selectedHotelIndex: 0,
    hotel: ranked[0], // back-compat: top-ranked hotel
  };
}

